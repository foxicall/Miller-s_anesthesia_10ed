import { expect, test } from '@playwright/test'

test('offline-first navigation, Chinese search, responsive directory and reading tools', async ({ page, context }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('./')
  const manifest = await page.evaluate(async () => (await fetch(document.querySelector<HTMLLinkElement>('link[rel="manifest"]')!.href)).json())
  expect(manifest.name).toBe("米勒麻醉學 (Miller's Anesthesia 10e)")
  expect(manifest.short_name).toBe('米勒麻醉學')
  expect(manifest.theme_color).toBe('#0f172a')
  await expect(page.getByRole('heading', { name: /讓臨床知識，\s*隨手可及。/ })).toBeVisible()
  await expect(page.getByText('已可離線閱讀', { exact: true })).toBeVisible({ timeout: 180_000 })
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  await expect.poll(() => page.evaluate(() => Boolean(navigator.serviceWorker.controller))).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: `test-results/${testInfo.project.name}-home.png`, fullPage: true })
  // Exercise the actual appearance switch, including the mobile navigation.
  if (testInfo.project.name === 'mobile') await page.getByRole('button', { name: '開啟導覽選單' }).click()
  await page.getByRole('switch', { name: '切換為深色模式' }).click()
  await expect(page.locator('html')).toHaveClass(/dark/)
  if (testInfo.project.name === 'mobile') await page.getByRole('button', { name: '開啟導覽選單' }).click()
  await page.screenshot({ path: `test-results/${testInfo.project.name}-dark.png`, fullPage: true })
  if (testInfo.project.name === 'mobile') await page.getByRole('button', { name: '開啟導覽選單' }).click()
  await page.getByRole('switch', { name: '切換為淺色模式' }).click()
  if (testInfo.project.name === 'mobile') await page.getByRole('button', { name: '開啟導覽選單' }).click()

  // Search has never been opened, and chapter 87 has never been visited.
  await context.setOffline(true)
  await page.reload()
  await expect(page.getByText('離線閱讀中', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '搜尋章節、醫學名詞或藥物…' }).click()
  const search = page.locator('#localsearch-input')
  await expect(search).toBeVisible()
  await search.fill('離線閱讀')
  await expect(page.locator('.VPLocalSearchBox .result').first()).toBeVisible()
  await search.fill('氣道管理')
  await expect(page.locator('.VPLocalSearchBox .result').filter({ hasText: '成人氣道管理' }).first()).toBeVisible()
  await search.fill('propofol')
  await expect(page.locator('.VPLocalSearchBox .result').first()).toBeVisible()
  await page.keyboard.press('Escape')
  await page.goto('./chapters/ch-87.html')
  await expect(page.locator('.vp-doc h1')).toContainText('醫學文獻判讀')
  await expect(page.getByText('離線閱讀中', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.locator('.vp-doc h1')).toBeVisible()

  await page.goto('./chapters/ch-21.html')
  await expect(page.locator('.vp-doc h1')).toContainText('靜脈麻醉藥')
  await expect(page.locator('.chapter-original-title')).toHaveText('Intravenous Anesthetics')
  await page.locator('details summary').first().click()
  const originalImage = page.locator('details img').first()
  await originalImage.scrollIntoViewIfNeeded()
  await expect.poll(() => originalImage.evaluate(image => (image as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(await page.locator('.vp-doc table').first().evaluate(table => getComputedStyle(table).overflowX)).toBe('auto')
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: `test-results/${testInfo.project.name}-chapter.png` })

  await page.goto('./guide.html')
  if (testInfo.project.name === 'mobile') {
    await page.getByRole('button', { name: '章節導覽', exact: true }).click()
    await expect(page.getByRole('dialog', { name: '章節導覽' })).toBeVisible()
    await page.locator('.outline-dialog').getByRole('link', { name: '安裝到主畫面', exact: true }).click()
    await expect(page.locator('.outline-dialog')).not.toBeVisible()
    await expect(page).toHaveURL(/#%E5%AE%89/)
    await page.getByRole('button', { name: '快速回到頂部', exact: true }).click()
    await expect.poll(() => page.evaluate(() => window.scrollY)).toBeLessThan(10)
  }
  await page.goto('./chapters/')
  await page.getByRole('searchbox', { name: '篩選章號或章節名稱' }).fill('87')
  await expect(page.locator('.chapter-row')).toHaveCount(1)
  await expect(page.locator('.chapter-row')).toHaveAttribute('href', /ch-87\.html$/)
  await page.getByRole('searchbox', { name: '篩選章號或章節名稱' }).fill('呼吸道管理')
  await expect(page.locator('.chapter-row')).toHaveCount(1)
  await expect(page.locator('.chapter-row')).toContainText('成人氣道管理')
  await page.getByRole('searchbox', { name: '篩選章號或章節名稱' }).fill('Airway Management')
  await expect(page.locator('.chapter-row')).toHaveCount(1)
  await page.getByRole('searchbox', { name: '篩選章號或章節名稱' }).fill('不存在的章名')
  await expect(page.getByText('沒有符合條件的章節。請調整關鍵字或取消篩選。')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.goto('./404.html')
  await expect(page.getByText('找不到此頁面', { exact: true })).toBeVisible()
  expect(errors).toEqual([])
})
